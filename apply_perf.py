seq = max(int(p["id"][1:]) for p in players)
added, changed, missing = [], [], []

for spec in NEW:
    seq += 1
    p = {"id": f"P{seq:03d}", "name": spec["name"], "pos": spec["pos"], "throws": spec["throws"],
         "type": "HS", "hs": spec["hs"], "univ": None, "foreign": None, "indy": None,
         "talent": spec["talent"], "var": spec["var"], "conf": spec["conf"],
         "note": spec["note"], "eligible": True, "elig_note": "", "college_grad": False}
    scout = spec["talent"]
    p["scout"] = scout
    p["perf"] = {"score": spec["perf"], "alpha": spec["alpha"], "record": spec["note"], "src": spec["src"]}
    p["talent"] = round(scout * (1 - spec["alpha"]) + spec["perf"] * spec["alpha"], 1)
    players.append(p)
    added.append((p["name"], p["hs"], scout, p["talent"]))

for name, school, perf, alpha, nvar, nconf, rec, src in PERF:
    p = find(name, school)
    if not p:
        missing.append((name, school)); continue
    scout = p["talent"]
    p["scout"] = scout
    p["talent"] = round(scout * (1 - alpha) + perf * alpha, 1)
    p["var"] = nvar
    p["conf"] = nconf
    p["perf"] = {"score": perf, "alpha": alpha, "record": rec, "src": src}
    if not p["note"]:            # 기존 스카우팅 코멘트는 유지하고 성적은 perf.record 로 분리 보관
        p["note"] = ""
    changed.append((name, scout, p["talent"], round(p["talent"] - scout, 1)))

# perf 미보유 선수는 scout=talent 로 명시
for p in players:
    p.setdefault("scout", p["talent"])
    p.setdefault("perf", None)

