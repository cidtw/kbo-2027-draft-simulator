        if hit:                        # 기존 등재 선수 → KBSA 값으로 보강만
            hit["ht"], hit["wt"] = ht, wt
            if tb and not hit.get("tb"):
                hit["tb"], hit["tb_conf"] = TB.get(tb, ""), "official"
            updated += 1
            continue
        seq += 1
        players.append({
            "id": f"P{seq:03d}", "name": name, "pos": pos,
            "throws": THROW.get(tb, "") if pos == "P" else "",
            "type": "COL", "hs": None, "univ": school, "foreign": None, "indy": None,
            "talent": BASE_T[maxg], "scout": BASE_T[maxg], "perf": None,
            "var": 10, "conf": "low",
            "note": f"KBSA 대학부 공식 명단 {grade}학년(졸업예정) — 스카우팅 평가 미확보",
            "eligible": True,
            "elig_note": ("2년제 졸업예정(2학년)" if maxg == 2 else
                          "3년제 졸업예정(3학년)" if maxg == 3 else "4년제 졸업예정(4학년)"),
            "college_grad": True, "applied": None,
            "ht": ht, "wt": wt,
            "kbsa": {"grade": grade, "pos": pos, "ht": ht, "wt": wt, "tb": TB.get(tb, ""),
                     "src": "KBSA 2026 대학부 등록명단"},
            "tb": TB.get(tb, ""), "tb_conf": "official" if tb else "unknown",
        })
        added += 1

